// Вход: строка с задачей проектирования (или {task: "..."}).
const task = (typeof args === 'string' && args.trim()) ? args.trim()
           : (args && typeof args.task === 'string') ? args.task.trim() : null
if (!task) return { error: 'args обязателен: строка с задачей проектирования (или {task})' }

const GROUND = 'Проектная задача 1С: ' + task + '\n' +
  'Режим: ТОЛЬКО проектирование, ничего не редактировать. Отвечай по-русски; комментарии в примерах кода — по-русски. ' +
  'Код и ВСЕ имена метаданных — по языковому профилю ПРОЕКТА (en|ru, docs/code/language-profile.md), не смешивать; ' +
  'синонимы/представления — на всех языках профиля. Стандарты 1С обязательны (std469 для имён).\n' +
  'work-through-tools п.3: КАЖДОЕ проектное решение согласуй с инструментами — подключай их через ToolSearch ' +
  '(mcp__*v8std__* стандарты, mcp__*bsl-platform__*/mcp__*bsl-context__* API платформы, mcp__*code-index__* существующий код/дубли, ' +
  'mcp__edt-mcp__* метаданные живого EDT) и файлами базы знаний docs/, docs-project/ (проектные доки экземпляра, если папка есть) и .claude/skills/ (bsp — механизмы БСП). ' +
  'Имена инструментов серверов плагина: в мастере — mcp__v8std__…, в проекте с плагином — mcp__plugin_ones-core_v8std__…; ищи их ToolSearch по короткому имени сервера (v8std, code-index, bsl-platform, bsl-context), а не select: по полному имени. ' +
  'Решение без обоснования стандартом/БСП/API помечай как «гипотеза». Своё предлагать только если штатного нет — и показать, чем проверял.'

const ROLE_SCHEMA = {
  type: 'object', additionalProperties: false,
  properties: {
    role: { type: 'string' },
    decisions: { type: 'array', items: {
      type: 'object', additionalProperties: false,
      properties: {
        decision:  { type: 'string' },
        groundedIn:{ type: 'string', description: 'стандарт/механизм БСП/метод API или «гипотеза»' },
        tool:      { type: 'string', description: 'какой инструмент подтвердил' },
      }, required: ['decision', 'groundedIn'] } },
    risks: { type: 'array', items: { type: 'string' } },
    openQuestions: { type: 'array', items: { type: 'string' } },
  }, required: ['role', 'decisions'],
}
const CRIT_SCHEMA = {
  type: 'object', additionalProperties: false,
  properties: {
    findings: { type: 'array', items: {
      type: 'object', additionalProperties: false,
      properties: {
        severity: { type: 'string', enum: ['high', 'medium', 'low'] },
        issue:    { type: 'string' },
        roles:    { type: 'string' },
        fix:      { type: 'string' },
      }, required: ['severity', 'issue', 'fix'] } },
  }, required: ['findings'],
}

// ДВОЙНИК-МАЯЧОК: полные версии ролей — .claude/agents/{architect,analyst,ui-designer,programmer,tester}-1c.md.
// Скрипт не имеет доступа к ФС, поэтому p-строки ролей продублированы; правишь роль там — выровняй формулировку здесь.
// Критик консилиума ≠ ревьюер кода: он проверяет ПРОЕКТНЫЕ решения и проекции (архитектура/БСП/API/стандарты на
// уровне ЗАМЫСЛА), а не готовый BSL — поэтому кодовых дефектов у него намеренно нет. Ревью готового кода —
// reviewer-1c при реализации (это РАЗНЫЕ роли, не двойники; эквивалентности чек-листов здесь не обещаем).
const ROLES = [
  { key: 'архитектор',   p: 'Ты АРХИТЕКТОР. Слои/модули/подсистемы, единый префикс + суффиксы std469, швы расширяемости (Переопределяемый/ОпределяемыеТипы; шов заводится только при двух и более реализациях — naming-and-module-design, в шве только делегация), развязка с хостом, компактность без дублей. Ядро и точки входа: правило — в серверном общем модуле/модуле менеджера и проверяемо YAXUnit, форма/сервис/регламентное задание/обмен тонкие и правило не пересчитывают, зависимости внутрь; ревью по фазам: границы → зависимости → сокрытие → местное качество. Согласуй структуру и имена с v8std, существующее — с code-index/edt-mcp (без EDT — code-index и meta-info).' },
  { key: 'аналитик',     p: 'Ты АНАЛИТИК. Бизнес-процессы, потоки данных, объектная модель (объекты/реквизиты/движения/регистры), граничные случаи (возвраты, отмены, дубли, пустые значения). Существующие объекты и реквизиты сверяй фактом (edt-mcp/code-index) — не выдумывать имена и не плодить дубли.' },
  { key: 'дизайнер',     p: 'Ты ДИЗАЙНЕР ИНТЕРФЕЙСА. Формы управляемые и обычные (архетипы, раскладка, DataPath), АРМ, командный интерфейс, UX-сценарии. Стандарты интерфейса — v8std; реальные реквизиты для DataPath — edt-mcp (get_metadata_details), без EDT — meta-info/code-index, не вслепую; управляемые формы — конвейер 1c-forms (гибрид с edt-mcp), обычные — минимальный дифф и проверка загрузкой в тестовую базу.' },
  { key: 'программист',  p: 'Ты ПРОГРАММИСТ 1С. Реализуемость: механизмы БСП (скилл bsp в .claude/skills/bsp), API платформы (bsl-platform/bsl-context, validate_module для каждого нетривиального вызова), существующий код — code-index, транзакции/блокировки/производительность. Порядок: одно поведение за раз, тест YAXUnit первым, новое поведение — в ядро, точка входа только зовёт его; без самодельных замен штатным проверкам. Своё — только если инструменты подтвердили, что штатного нет, с доказательством.' },
  { key: 'тестировщик',  p: 'Ты ТЕСТИРОВЩИК. Тест-план «что и чем докажем»: юнит-тесты YAXUnit (тестовое расширение, один тест — одно поведение), функциональные кейсы «вход → ожидаемо», граничные случаи аналитика → регрессия, каждому багу — воспроизводящий тест. Тест падает на правдоподобной ошибочной реализации; юнит-тесты — на ядро, функциональный кейс формы их не заменяет; «ядро ради теста» (форма решает тот же вопрос своим кодом) — дефект. Тестируемое поведение сверяй фактом (edt-mcp/code-index), API — bsl-platform/bsl-context; только тестовая база.' },
]

phase('Консилиум')
// Барьер осознанно: критику нужны ВСЕ проекции сразу (кросс-сверка ролей).
// Упавший агент в parallel() — это null, и оркестрация едет дальше: критик и синтезатор молча работали бы по
// неполному консилиуму (в экземпляре 5 из 7 агентов умерли на кириллических ключах схемы, а результат выглядел
// полноценным — находка 18.09.2026). Поэтому потери считаются, логируются и передаются дальше явно.
const rawViews = await parallel(ROLES.map(r => () =>
  agent(GROUND + '\n\n' + r.p, { label: 'роль:' + r.key, phase: 'Консилиум', schema: ROLE_SCHEMA })
))
const views = rawViews.filter(Boolean)
const lostRoles = ROLES.filter((r, i) => !rawViews[i]).map(r => r.key)
if (lostRoles.length) log('ВНИМАНИЕ: не вернулись роли — ' + lostRoles.join(', ') + '; консилиум НЕПОЛНЫЙ, это отражено в плане')
const LOST_NOTE = lostRoles.length ? '\nВНИМАНИЕ: проекций ролей ' + lostRoles.join(', ') + ' НЕТ (агенты не вернулись) — их срез не покрыт; отметь это явно и не выдавай план за полный.' : ''

phase('Критика')
const critique = await agent(
  GROUND + '\n\nТы СОСТЯЗАТЕЛЬНЫЙ КРИТИК консилиума. Проекции ролей (JSON):\n' + JSON.stringify(views) +
  '\nНайди: противоречия между ролями; решения без groundedIn (или с фиктивным); нарушения стандартов; ' +
  'изобретение своего при существующем БСП/платформенном механизме (проверь инструментами сам); пропущенные риски.' + LOST_NOTE,
  { label: 'критик', phase: 'Критика', schema: CRIT_SCHEMA })

phase('Синтез')
const plan = await agent(
  GROUND + '\n\nТы СИНТЕЗАТОР консилиума (не конвейер: взвесь всё и сведи к ЕДИНОМУ лучшему варианту).\n' +
  'Проекции ролей: ' + JSON.stringify(views) + '\nЗамечания критика: ' + JSON.stringify(critique) +
  '\nВерни согласованный план: Архитектура · Объектная модель · UI/АРМ · Реализация (этапы) · Тесты/приёмка (тест-план: юнит-тесты, функциональные кейсы) · Риски · Открытые вопросы. ' +
  'Каждый пункт — с обоснованием (стандарт/БСП/API + каким инструментом подтверждено) либо пометкой «гипотеза: проверить X».\n' +
  'ОБЯЗАТЕЛЬНО отдельным разделом «Дерево решений» — по каждому решению плана узел: (1) узел (что решается); ' +
  '(2) альтернативы — минимум две реально рассмотренные; (3) рекомендация: какая роль даёт + на что опирается ' +
  '(стандарт/БСП/API/факт из кода или «гипотеза»); (4) необратимость — что придётся переделывать, если решение неверно ' +
  '(строку кода? метаданные с данными в базе?) и цена ошибки; (5) если узел прошёл фильтр необратимости ' +
  '(дорого откатить + причина неочевидна через год + был реальный размен — docs/design/decision-records-and-glossary.md) — пометь его «→ ADR»: ' +
  'оформляется как docs-project/adr/NNNN-slug.md скиллом engineering:architecture, ЛЕНИВО (только при реальном размене, пустой каркас не заводить). ' +
  'Схлопнутая молча развилка — дефект синтеза: ' +
  'узлы дерева и есть то, что уходит пользователю на согласование (docs/design/five-role-design-review.md, docs/design/requirements-by-interview.md).' + LOST_NOTE,
  { label: 'синтез', phase: 'Синтез' })

return { task: task, plan: plan, critique: critique, lostRoles: lostRoles,
         roles: views.map(v => ({ role: v.role, decisions: (v.decisions || []).length })) }
